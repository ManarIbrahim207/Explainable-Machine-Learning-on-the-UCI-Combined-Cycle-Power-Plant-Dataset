plt.grid(True)
plt.show()

from sklearn.model_selection import KFold

kf = KFold(n_splits=5, shuffle=True, random_state=42)
r2_scores = []

for train_index, val_index in kf.split(X):
    X_train_fold, X_val_fold = X.iloc[train_index], X.iloc[val_index]
    y_train_fold, y_val_fold = y.iloc[train_index], y.iloc[val_index]

    # Create a new pipeline for each fold to avoid data leakage (especially for PCA)
    pipeline_kfold = make_pipeline(
        StandardScaler(),
        PCA(n_components=2),
        Ridge()
    )

    pipeline_kfold.fit(X_train_fold, y_train_fold)
    fold_r2 = pipeline_kfold.score(X_val_fold, y_val_fold)
    r2_scores.append(fold_r2)

print(f"R^2 scores for each fold: {r2_scores}")
print(f"Average R^2 score across folds: {np.mean(r2_scores):.3f}")
print(f"Standard deviation of R^2 scores: {np.std(r2_scores):.3f}")

"""## 5. Random Forest Model with Hyperparameter Tuning

This section trains a **Random Forest Regressor** using **GridSearchCV** for optimal hyperparameters:
- **n_estimators**: Number of trees (100, 200)
- **max_features**: Features to consider per split ('sqrt')
- **max_depth**: Tree depth control (None, 10)
- **min_samples_split**: Minimum samples for split (2, 5)

We use 3-fold cross-validation and R² scoring. The tuned RF typically outperforms the linear baseline by capturing non-linear relationships in power plant data (temperature → power output is highly non-linear).

"""

from sklearn.model_selection import GridSearchCV

# Define the pipeline for Random Forest
pipe_rf = make_pipeline(
    RandomForestRegressor(random_state=42)
)

# Define the parameter grid for Random Forest Regressor
param_grid_rf = {
    'randomforestregressor__n_estimators': [100, 200], # Number of trees in the forest
    'randomforestregressor__max_features': ['sqrt'], # Number of features to consider when looking for the best split
    'randomforestregressor__max_depth': [None, 10], # Maximum number of levels in tree
    'randomforestregressor__min_samples_split': [2, 5] # Minimum number of samples required to split an internal node
}

grid_search_rf = GridSearchCV(
    pipe_rf, # The pipeline containing the RandomForestRegressor model
    param_grid=param_grid_rf, # The grid of hyperparameters to search
    cv=3, # Number of folds for cross-validation
    scoring="r2", # Metric to evaluate model performance (R-squared)
    n_jobs=-1 # Use all available CPU cores for parallel processing
)
# Fit GridSearchCV to the training data to find the best hyperparameters
# .values.ravel() is used to convert the y_train DataFrame into a 1D numpy array
# which is often required by scikit-learn models for target variables.
grid_search_rf.fit(X_train, y_train.values.ravel())

# Print the best parameters and best score
print(f"Best parameters found for Random Forest: {grid_search_rf.best_params_}")
print(f"Best R^2 score found for Random Forest: {grid_search_rf.best_score_:.3f}")

# Evaluate on the test set using the best estimator
best_estimator_rf = grid_search_rf.best_estimator_
y_pred_rf = best_estimator_rf.predict(x_test)
test_r2_rf = r2_score(y_test, y_pred_rf)
print(f"Test R^2 score with best Random Forest estimator: {test_r2_rf:.3f}")

# Calculate and print MAE and RMSE
mae_rf = mean_absolute_error(y_test, y_pred_rf)
rmse_rf = np.sqrt(mean_squared_error(y_test, y_pred_rf))
print(f"Test MAE with best Random Forest estimator: {mae_rf:.3f}")
print(f"Test RMSE with best Random Forest estimator: {rmse_rf:.3f}")

