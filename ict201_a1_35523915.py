"""## 4. Linear Regression Baseline Model

This section establishes a baseline model using **Ridge Regression** (L2 regularization) with a preprocessing pipeline:
- **StandardScaler**: Normalizes features to zero mean and unit variance
- **PCA**: Reduces dimensionality to 2 components for better generalization and faster training
- **Ridge Regressor**: A simple, interpretable linear model that serves as a baseline for comparison

We evaluate using cross-validation (5-fold) and test-set R² score to ensure robust estimates.

"""

import matplotlib.pyplot as plt
import seaborn as sns

plt.figure(figsize=(8, 6))
sns.scatterplot(x=y_test.values.flatten(), y=y_pred.flatten())
plt.plot([y_test.min(), y_test.max()], [y_test.min(), y_test.max()], 'r--', lw=2)
