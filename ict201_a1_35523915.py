"""## 7. Local Explainability with LIME

This section applies LIME (Local Interpretable Model-agnostic Explanations) to explain individual predictions. LIME works by:
- Fitting a simple interpretable model (e.g., linear regression) around a specific test instance
- Weighting samples by their proximity to that instance
- Ranking features by their contribution to that local prediction

Together with SHAP, LIME enables both *why does the model predict this value overall* (global) and *why did it predict this specific value for this instance* (local) interpretability.

"""

# Use DataFrames instead of raw arrays
# Create copies of X_train and x_test to ensure no modifications to original dataframes
# Ensure cell tfuVpJbLJHJ is executed to define X_train and x_test
X_train_df = X_train.copy()
X_test_df  = x_test.copy()
# Get the list of feature names from the training DataFrame
feature_names = X_train_df.columns.tolist()

from lime.lime_tabular import LimeTabularExplainer
import numpy as np

# Initialize the LIME Tabular Explainer
explainer_lime = LimeTabularExplainer(
    training_data=X_train_df.values,  # LIME expects numpy array for training data
    feature_names=feature_names,      # Provide feature names for readability in explanations
    class_names=y.columns.tolist(), # The name of the target variable(s)
    mode="regression",                # Specify that this is a regression problem
    discretize_continuous=True        # Discretize continuous features for simpler explanations
)

# Wrap predict_fn so it receives a DataFrame with correct column names
# LIME calls predict_fn with numpy arrays, but our model was trained with DataFrames.
# This wrapper converts the numpy array back to a DataFrame with correct column names
# before passing it to the model's predict method.
def rf_predict_fn(x):
    x_df = pd.DataFrame(x, columns=feature_names)
    return best_rf.predict(x_df)

# Select an instance from the test set to explain (e.g., the first instance, index 0)
i = 0  # index of test instance
# Generate a LIME explanation for the chosen instance.
# data_row: The specific instance from the test set to explain.
# predict_fn: The function that LIME will use to get predictions from the model.
# num_features: The number of features to include in the explanation.
exp = explainer_lime.explain_instance(
    data_row=X_test_df.iloc[i].values,  # Pass the values (numpy array) of the selected instance
    predict_fn=rf_predict_fn,
    num_features=5
)

# Display the LIME explanation as an interactive graph
exp.show_in_notebook(show_all=False)

lime_html = exp.as_html()
print("LIME Explanation HTML extracted successfully.")

from IPython.display import HTML

